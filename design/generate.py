"""Generate and verify the shared white-paper design tokens. No network.

Run: python design/generate.py
Check: python design/generate.py --check
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'design' / 'tokens.json'


def outputs(tokens: dict) -> dict[Path, str]:
    header = '// GENERATED by design/generate.py from design/tokens.json — DO NOT EDIT.\n'
    js = header + 'export const tokens = Object.freeze(' + json.dumps(tokens, ensure_ascii=True, separators=(',', ':')) + ');\n'
    css = ['/* GENERATED by design/generate.py from design/tokens.json — DO NOT EDIT. */', ':root {']
    for key, value in tokens['colors'].items():
        css.append(f'  --color-{key}: {value};')
    for key, value in tokens['fontFamilies'].items():
        css.append(f'  --font-{key}: {value};')
    for key, value in tokens['fontSizes'].items():
        css.append(f'  --font-size-{key}: {value}px;')
    for key, value in tokens['spacing'].items():
        css.append(f'  --space-{key}: {value}px;')
    for key, value in tokens['radii'].items():
        css.append(f'  --radius-{key}: {value}px;')
    css.extend((f'  --shadow-paper: {tokens["shadow"]};',
                f'  --motion-short: {tokens["motion"]["shortMs"]}ms;',
                f'  --motion-medium: {tokens["motion"]["mediumMs"]}ms;', '}', ''))
    return {
        ROOT / 'desktop/src/design/tokens.js': js,
        ROOT / 'mobile/src/design/tokens.js': js,
        ROOT / 'desktop/src-ui/src/design-tokens.css': '\n'.join(css),
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    tokens = json.loads(SOURCE.read_text(encoding='utf-8'))
    assert len(tokens['colors']) == 13, 'Palette drift'
    for path, content in outputs(tokens).items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != content:
                raise SystemExit(f'Generated design artifact out of sync: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8')
    print('Shared tokens are synchronized.' if args.check else 'Shared tokens generated.')


if __name__ == '__main__':
    main()
